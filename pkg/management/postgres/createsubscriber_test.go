func TestCreateSubscriberMarker(t *testing.T) {
	pgData := t.TempDir()
	marker, err := ReadCreateSubscriberMarker(pgData)
	if err != nil || marker != nil {
		t.Fatalf("no marker expected: %v, %v", marker, err)
	}

	want := CreateSubscriberMarker{
		Engine:        CreateSubscriberEngineEmulated,
		Major:         14,
		ConsistentLSN: "0/3000148",
		PromotedLSN:   "0/30001C0",
		Databases:     []CreateSubscriberDatabase{{Name: "app", OID: 16384, Object: "cnpgsub_x_16384"}},
	}
	if err := WriteCreateSubscriberMarker(pgData, want); err != nil {
		t.Fatal(err)
	}
	got, err := ReadCreateSubscriberMarker(pgData)
	if err != nil {
		t.Fatal(err)
	}
	if got.PromotedLSN != want.PromotedLSN || got.Databases[0].Object != "cnpgsub_x_16384" {
		t.Fatalf("unexpected marker %+v", got)
	}
}
